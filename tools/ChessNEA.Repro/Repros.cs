using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;

namespace ChessNEA.Repro
{
    internal sealed class ReproResult
    {
        public string Id { get; set; }
        public string Title { get; set; }
        public string Position { get; set; }
        public string Expected { get; set; }
        public string Observed { get; set; }
        /// <summary>REPRODUCED, NOT_REPRODUCED, CORRECT (control case) or ERROR.</summary>
        public string Status { get; set; }
    }

    /// <summary>
    /// Focused reproductions of suspected defects in the original engine (commit 396744d).
    /// Each case builds a position, calls the engine's own functions and compares the
    /// observed behaviour with the chess rules. Nothing here modifies engine code.
    /// </summary>
    internal static class Repros
    {
        // Same value as the private Bot.largenumber constant.
        public const int Large = 99999999;

        public static List<ReproResult> RunAll()
        {
            var cases = new List<Func<ReproResult>>
            {
                SearchLeaksKingHasMoved,
                SearchCastlingLeavesRook,
                KingsideCastlingThroughCheck,
                QueensideCastlingOutOfCheck,
                KingsideCastlingOutOfCheckControl,
                KingMayStepNextToEnemyKing,
                KingAdjacencyCrashesSearch,
                BotPromotionUsesWrongX,
                SearchIgnoresPromotion,
                SearchEnPassantLeavesCapturedPawn,
                BotDoublePushNotRecorded,
                MateScorePrefersSlowerMate,
            };
            var results = cases.Select(Run).ToList();
            results.AddRange(InsufficientMaterialCases());
            return results;
        }

        static ReproResult Run(Func<ReproResult> f)
        {
            try { return f(); }
            catch (Exception e)
            {
                return new ReproResult { Id = f.Method.Name, Title = f.Method.Name, Status = "ERROR", Observed = e.ToString() };
            }
        }

        static bool Contains(List<Bot.Move> moves, string from, string to)
        {
            var (fc, fr) = Positions.Sq(from);
            var (tc, tr) = Positions.Sq(to);
            return moves.Any(m => m.prevcol == fc && m.prevrow == fr && m.nextcol == tc && m.nextrow == tr);
        }

        static Bot.Move Find(List<Bot.Move> moves, string from, string to)
        {
            var (fc, fr) = Positions.Sq(from);
            var (tc, tr) = Positions.Sq(to);
            return moves.First(m => m.prevcol == fc && m.prevrow == fr && m.nextcol == tc && m.nextrow == tr);
        }

        // R01: Bot.makeMove sets King.hasMoved = true; Bot.undoMove never restores it.
        static ReproResult SearchLeaksKingHasMoved()
        {
            const string fen = "rnbqkbnr/pppp1ppp/8/4p3/4P3/5N2/PPPP1PPP/RNBQKB1R b KQkq - 1 2";
            var b = Positions.FromFen(fen);
            var before = new Snapshot(b);
            b.bot.Minimax(b, 2, -Large, Large);
            var diffs = before.Diff(b);
            return new ReproResult
            {
                Id = "R01", Title = "Search does not restore King.hasMoved",
                Position = fen + "  (Minimax depth 2, black to move)",
                Expected = "Position state identical before and after the search",
                Observed = diffs.Count == 0 ? "no differences" : string.Join("; ", diffs),
                Status = diffs.Count == 0 ? "NOT_REPRODUCED" : "REPRODUCED",
            };
        }

        // R02: castling is generated by King.findMoves but Bot.makeMove only moves the king.
        static ReproResult SearchCastlingLeavesRook()
        {
            const string fen = "4k2r/8/8/8/8/8/8/4K3 b k - 0 1";
            var b = Positions.FromFen(fen);
            var moves = b.bot.findmoves(false);
            if (!Contains(moves, "e8", "g8"))
                return new ReproResult { Id = "R02", Title = "Castling in search moves only the king", Position = fen, Status = "NOT_REPRODUCED", Observed = "castling not generated" };
            var m = Find(moves, "e8", "g8");
            b.bot.makeMove(b, m);
            string rookH8 = b.ChessBoard[0, 7] is Rook ? "rook still on h8" : "h8 empty";
            string f8 = b.ChessBoard[0, 5] is Rook ? "rook on f8" : "f8 empty";
            b.bot.undoMove(b, m);
            bool bug = rookH8 == "rook still on h8";
            return new ReproResult
            {
                Id = "R02", Title = "Castling in search moves only the king", Position = fen + "  (Bot.makeMove ke8-g8)",
                Expected = "King on g8 and rook on f8",
                Observed = $"king on g8, {rookH8}, {f8}",
                Status = bug ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R03: King.findMoves computes 165 + (60 * col + j): j pixels, not j squares.
        static ReproResult KingsideCastlingThroughCheck()
        {
            const string fen = "5r1k/8/8/8/8/8/8/4K2R w K - 0 1"; // black rook attacks f1
            var b = Positions.FromFen(fen);
            bool generated = Contains(b.bot.findmoves(true), "e1", "g1");
            return new ReproResult
            {
                Id = "R03", Title = "Kingside castling allowed through an attacked square", Position = fen,
                Expected = "Ke1-g1 not legal (f1 attacked by rook f8)",
                Observed = generated ? "Ke1-g1 returned by Bot.findmoves(true)" : "Ke1-g1 not returned",
                Status = generated ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R04: Board.check is never set to true, and the queenside loop tests d1 twice but never e1.
        static ReproResult QueensideCastlingOutOfCheck()
        {
            const string fen = "4r2k/8/8/8/8/8/8/R3K3 w Q - 0 1"; // white king in check from e8
            var b = Positions.FromFen(fen);
            bool inCheck = b.IsKingInCheck(true);
            bool generated = Contains(b.bot.findmoves(true), "e1", "c1");
            return new ReproResult
            {
                Id = "R04", Title = "Queenside castling allowed while in check", Position = fen,
                Expected = "Ke1-c1 not legal (king in check)",
                Observed = $"IsKingInCheck(white)={inCheck}; " + (generated ? "Ke1-c1 returned by Bot.findmoves(true)" : "Ke1-c1 not returned"),
                Status = generated ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // Control for R03/R04: the kingside loop happens to test e1, so castling out of check is rejected.
        static ReproResult KingsideCastlingOutOfCheckControl()
        {
            const string fen = "4r2k/8/8/8/8/8/8/4K2R w K - 0 1";
            var b = Positions.FromFen(fen);
            bool generated = Contains(b.bot.findmoves(true), "e1", "g1");
            return new ReproResult
            {
                Id = "R04c", Title = "Control: kingside castling while in check", Position = fen,
                Expected = "Ke1-g1 not legal (king in check)",
                Observed = generated ? "Ke1-g1 returned" : "Ke1-g1 not returned (the off-by-pixels loop re-tests e1 by accident)",
                Status = generated ? "REPRODUCED" : "CORRECT",
            };
        }

        // R05: Board.IsKingInCheck checks rooks, bishops, queens, knights and pawns, but not the enemy king.
        static ReproResult KingMayStepNextToEnemyKing()
        {
            const string fen = "8/8/8/8/8/4k3/8/4K3 w - - 0 1";
            var b = Positions.FromFen(fen);
            var moves = b.bot.findmoves(true);
            var bad = new[] { "d2", "e2", "f2" }.Where(s => Contains(moves, "e1", s)).ToList();
            return new ReproResult
            {
                Id = "R05", Title = "King may move next to the enemy king", Position = fen,
                Expected = "Only Kd1 and Kf1 are legal",
                Observed = "generated: " + string.Join(", ", moves.Select(Positions.MoveName)),
                Status = bad.Count > 0 ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R06: once a king can "legally" stand next to the other king, the search can capture a king,
        // after which IsKingInCheck dereferences a null king.
        static ReproResult KingAdjacencyCrashesSearch()
        {
            const string fen = "8/7p/8/4k3/8/4K3/P7/8 b - - 0 1";
            var b = Positions.FromFen(fen);
            try
            {
                var r = b.bot.Minimax(b, 2, -Large, Large);
                return new ReproResult
                {
                    Id = "R06", Title = "Search crashes after a king capture", Position = fen + "  (Minimax depth 2)",
                    Expected = "Search completes", Observed = $"completed: score {r.evaluation}, move {Positions.MoveName(r.move)}",
                    Status = "NOT_REPRODUCED",
                };
            }
            catch (Exception e)
            {
                return new ReproResult
                {
                    Id = "R06", Title = "Search crashes after a king capture", Position = fen + "  (Minimax depth 2)",
                    Expected = "Search completes", Observed = $"{e.GetType().Name} in {e.TargetSite?.DeclaringType?.Name}.{e.TargetSite?.Name}",
                    Status = "REPRODUCED",
                };
            }
        }

        // R07: Bot.move() builds the promoted queen with Rectangle(col, 425, ...) instead of Rectangle(165 + 60*col, ...).
        static ReproResult BotPromotionUsesWrongX()
        {
            const string fen = "7k/8/8/8/8/8/1p6/R6K b - - 0 1";
            var b = Positions.FromFen(fen);
            b.bot.move();
            Piece q = null; int qc = -1;
            for (int c = 0; c < 8; c++) if (b.ChessBoard[7, c] is Queen) { q = b.ChessBoard[7, c]; qc = c; }
            if (q == null)
                return new ReproResult { Id = "R07", Title = "Bot promotion stores wrong X coordinate", Position = fen, Status = "NOT_REPRODUCED", Observed = "bot did not promote; board:\n" + Positions.Diagram(b) };
            string after;
            try { b.bot.evaluate(); after = "Bot.evaluate() afterwards succeeded"; }
            catch (Exception e) { after = $"Bot.evaluate() afterwards throws {e.GetType().Name}"; }
            int expectedX = 165 + 60 * qc;
            return new ReproResult
            {
                Id = "R07", Title = "Bot promotion stores wrong X coordinate", Position = fen + "  (Bot.move)",
                Expected = $"Queen on {Positions.SqName(qc, 7)} with Position.X = {expectedX}",
                Observed = $"Queen in array at {Positions.SqName(qc, 7)} with Position.X = {q.Position.X}; {after}",
                Status = q.Position.X != expectedX ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R08: inside the search a pawn reaching the last rank stays a pawn, and the black pawn table
        // scores rank 1 (0) worse than rank 2 (-50 for black = +50 for the bot).
        static ReproResult SearchIgnoresPromotion()
        {
            const string fen = "7k/8/8/8/8/8/1p6/7K b - - 0 1";
            var b = Positions.FromFen(fen);
            var moves = b.bot.findmoves(false);
            var scores = new List<string>();
            int promoScore = 0, bestOther = int.MinValue;
            foreach (var m in moves)
            {
                b.bot.makeMove(b, m);
                int s = b.bot.Minimax(b, 0, -Large, Large).evaluation;
                b.bot.undoMove(b, m);
                scores.Add($"{Positions.MoveName(m)}={s}");
                if (m.piece is Pawn) promoScore = s; else bestOther = Math.Max(bestOther, s);
            }
            return new ReproResult
            {
                Id = "R08", Title = "Search does not model promotion", Position = fen + "  (static eval after each black move)",
                Expected = "Promotion b2-b1 scores far above any king move (pawn becomes a queen)",
                Observed = string.Join(", ", scores),
                Status = promoScore <= bestOther ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R09: en passant is generated by Pawn.findMoves but Bot.makeMove does not remove the captured pawn.
        static ReproResult SearchEnPassantLeavesCapturedPawn()
        {
            const string fen = "k7/8/8/8/3pP3/8/8/7K b - e3 0 1";
            var b = Positions.FromFen(fen);
            var moves = b.bot.findmoves(false);
            if (!Contains(moves, "d4", "e3"))
                return new ReproResult { Id = "R09", Title = "En passant in search leaves the captured pawn", Position = fen, Status = "NOT_REPRODUCED", Observed = "d4xe3 not generated" };
            var m = Find(moves, "d4", "e3");
            b.bot.makeMove(b, m);
            bool stillThere = b.ChessBoard[4, 4] is Pawn p && p.IsWhite;
            b.bot.undoMove(b, m);
            return new ReproResult
            {
                Id = "R09", Title = "En passant in search leaves the captured pawn", Position = fen + "  (Bot.makeMove d4xe3)",
                Expected = "White pawn on e4 removed",
                Observed = stillThere ? "white pawn still on e4 after the capture" : "e4 empty",
                Status = stillThere ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R10: Bot.makeMove never sets Pawn.movedtwoSquares, so the opponent cannot capture the bot's pawn en passant.
        static ReproResult BotDoublePushNotRecorded()
        {
            const string fen = "rnbqkbnr/pppppppp/8/4P3/8/8/PPPP1PPP/RNBQKBNR b KQkq - 0 1";
            var b = Positions.FromFen(fen);
            var m = Find(b.bot.findmoves(false), "d7", "d5");
            b.bot.makeMove(b, m);
            bool epAvailable = Contains(b.bot.findmoves(true), "e5", "d6");
            return new ReproResult
            {
                Id = "R10", Title = "Bot double push does not enable en passant", Position = fen + "  (Bot.makeMove d7-d5)",
                Expected = "White may reply e5xd6 en passant",
                Observed = epAvailable ? "e5xd6 generated" : "e5xd6 not generated (movedtwoSquares never set by Bot.makeMove)",
                Status = epAvailable ? "NOT_REPRODUCED" : "REPRODUCED",
            };
        }

        // R11: mate scores are +/-(largenumber - depth) where depth is *remaining* depth, so a mate
        // found closer to the leaves (later) gets a higher score than a mate found sooner.
        static ReproResult MateScorePrefersSlowerMate()
        {
            const string fen = "k7/8/8/8/8/1r6/r7/7K b - - 0 1"; // ...Rb1# is mate in one
            var b = Positions.FromFen(fen);
            var root = b.bot.Minimax(b, 4, -Large, Large);

            var b2 = Positions.FromFen(fen);
            var mate1 = Find(b2.bot.findmoves(false), "b3", "b1");
            b2.bot.makeMove(b2, mate1);
            int mate1Score = b2.bot.Minimax(b2, 3, -Large, Large).evaluation;
            bool whiteHasMoves = b2.bot.findmoves(true).Count > 0;

            string chosen = Positions.MoveName(root.move);
            bool slower = root.evaluation > mate1Score && chosen != "rb3-b1";
            return new ReproResult
            {
                Id = "R11", Title = "Mate scoring prefers a slower mate", Position = fen + "  (Minimax depth 4)",
                Expected = "Root plays the mate in one rb3-b1",
                Observed = $"root move {chosen} score {root.evaluation} (= largenumber - {Large - root.evaluation}); " +
                           $"rb3-b1 scores {mate1Score} (= largenumber - {Large - mate1Score}); white has legal replies after rb3-b1: {whiteHasMoves}",
                Status = slower ? "REPRODUCED" : "NOT_REPRODUCED",
            };
        }

        // R12: Board.InsufficientMaterial (private) compared with FIDE dead-position cases.
        static IEnumerable<ReproResult> InsufficientMaterialCases()
        {
            MethodInfo mi = typeof(Board).GetMethod("InsufficientMaterial", BindingFlags.Instance | BindingFlags.NonPublic);
            var cases = new (string id, string fen, string label, bool expected, string why)[]
            {
                ("R12a", "k7/8/8/8/8/8/8/K7 w - - 0 1", "K v K", true, "no mate possible"),
                ("R12b", "k7/8/8/8/8/8/8/KB6 w - - 0 1", "KB v K", true, "no mate possible"),
                ("R12c", "kb6/8/8/8/8/8/8/K1B5 w - - 0 1", "KB v KB, same-colour bishops", true, "no mate possible"),
                ("R12d", "k7/8/8/8/8/8/8/KBN5 w - - 0 1", "KBN v K", false, "mate can be forced"),
                ("R12e", "kb6/8/8/8/8/8/8/KB6 w - - 0 1", "KB v KB, opposite-colour bishops", false, "a (help)mate exists, so not a dead position"),
                ("R12f", "k7/8/8/8/8/8/8/KNN5 w - - 0 1", "KNN v K", false, "a (help)mate exists, so not a dead position"),
                ("R12g", "k7/8/8/4p3/4P3/8/8/K7 w - - 0 1", "K+P v K+P, blocked pawns", false, "kings can capture pawns; mate still possible"),
            };
            foreach (var c in cases)
            {
                var b = Positions.FromFen(c.fen);
                bool observed = (bool)mi.Invoke(b, null);
                yield return new ReproResult
                {
                    Id = c.id, Title = $"InsufficientMaterial: {c.label}", Position = c.fen,
                    Expected = $"{c.expected} ({c.why})",
                    Observed = observed.ToString(),
                    Status = observed == c.expected ? "CORRECT" : "REPRODUCED",
                };
            }
        }
    }
